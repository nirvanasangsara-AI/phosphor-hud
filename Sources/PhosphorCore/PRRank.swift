import Foundation

/// A percentile table for public pull requests opened in one window.
/// Each band is one count. Zero public pull requests has no rank. Counts above 1000 use the 1000 row.
public struct PRRankTable: Codable, Equatable, Sendable {
    public var window: String
    public var builtAt: String
    public var bundled: Bool
    public var source: String
    public var bands: [Band]
    public var nextTier: NextTier?

    public struct Band: Codable, Equatable, Sendable {
        public var countLow: Int
        public var countHigh: Int
        /// Top share in percent, before display rounding. Low is the smallest of the six 7-day fits.
        public var topPercentLow: Double
        public var topPercentHigh: Double
    }

    /// Where the six fits each first reach a top share of 5% or less, as a range of weekly counts.
    public struct NextTier: Codable, Equatable, Sendable {
        public var topPercent: Int
        public var perWeekLow: Int
        public var perWeekHigh: Int
    }

    public struct Hit: Equatable, Sendable {
        public var topPercentLow: Double
        public var topPercentHigh: Double
        public var next: NextTier?
        public var builtAt: String
    }

    /// Whole numbers at 1% and above. One decimal place below 1%.
    public static func percentText(_ value: Double) -> String {
        if value < 1 {
            return String(format: "%.1f", locale: Locale(identifier: "en_US_POSIX"), value)
        }
        return String(Int(value.rounded()))
    }

    /// Nil when there are no public pull requests. Counts above 1000 use the last row.
    public func lookup(publicCount: Int) -> Hit? {
        guard publicCount > 0 else { return nil }
        let n = min(publicCount, 1000)
        guard let band = bands.first(where: { n >= $0.countLow && n <= $0.countHigh }) else { return nil }
        return Hit(topPercentLow: band.topPercentLow, topPercentHigh: band.topPercentHigh,
                   next: nextTier, builtAt: builtAt)
    }

    public static func decode(_ data: Data) -> PRRankTable? {
        try? JSONDecoder().decode(PRRankTable.self, from: data)
    }

    /// The 2026-11-28 GH Archive fits, generated by workers/pr-rank/src/snapshot.mjs.
    public static var bundled: PRRankTable {
        guard let url = Bundle.module.url(forResource: "PRRankSnapshot", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let table = decode(data) else {
            preconditionFailure("PR rank snapshot is missing from the PhosphorCore bundle")
        }
        return table
    }
}
